package demo

import (
	"fmt"
	"io"
	"strings"
)

// writeCRM writes the SQL script that creates and fills the CRM database. The
// Postgres container runs it the first time it starts.
func writeCRM(w io.Writer, c Company) error {
	var b strings.Builder
	b.WriteString(`-- Generated by "intarsia demo up". Do not edit: it is overwritten.
create table clientes (
    id           integer primary key,
    razao_social text not null,
    cnpj         text not null,
    cidade       text not null,
    uf           char(2) not null,
    segmento     text not null,
    vendedor     text not null,
    criado_em    date not null
);

insert into clientes (id, razao_social, cnpj, cidade, uf, segmento, vendedor, criado_em) values
`)
	for i, customer := range c.Customers {
		separator := ","
		if i == len(c.Customers)-1 {
			separator = ";"
		}
		fmt.Fprintf(&b, "    (%d, %s, %s, %s, %s, %s, %s, %s)%s\n",
			customer.ID,
			quote(customer.Name),
			quote(customer.CNPJ),
			quote(customer.City),
			quote(customer.State),
			quote(customer.Segment),
			quote(customer.Salesperson),
			quote(customer.CreatedAt.Format("2006-01-02")),
			separator,
		)
	}
	_, err := io.WriteString(w, b.String())
	return err
}

// quote writes a SQL string literal.
func quote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}
